import { defineConfig } from "tsdown";

/**
 * Build the browser half into the artifact the Harness Web page loads.
 *
 * The page hands each plugin bundle to its own module loader, so a client
 * artifact must be one `window.__ModuleLoader__.load({ id, factory })`
 * registration whose factory body is ordinary CommonJS: `react` and
 * `react/jsx-runtime` stay external (the page's module table provides them) and
 * are requested through the `require` the loader passes in. The banner and
 * footer below supply exactly that wrapper around tsdown's CJS output, which is
 * why the output is written next to `package.json` as `client.js` — the path
 * `exports["./client"]` publishes and the Host's bundle watcher polls.
 *
 * `clean` is off: the output directory is the package root, which holds the
 * package's own files.
 */
export default defineConfig({
  entry: ["src/client/index.tsx"],
  outDir: ".",
  clean: false,
  format: "cjs",
  platform: "browser",
  target: "es2022",
  dts: false,
  sourcemap: false,
  // React and the JSX runtime are page-provided baseline modules: they must stay
  // `require(...)` calls, never inlined into the bundle.
  deps: { neverBundle: [/^react(\/|$)/] },
  outputOptions: {
    entryFileNames: "client.js",
    // The loader contract is `factory(require) => exports`, so the wrapper also
    // owns the CommonJS bindings the compiled body writes its exports to.
    banner: [
      "// Generated by tsdown from src/client/index.tsx — do not edit; run `npm run build:client`.",
      "window.__ModuleLoader__.load({",
      '\tid: "@indexyz/dsh-autocompact",',
      "\tfactory: (require) => {",
      "\t\tvar module = { exports: {} };",
      "\t\tvar exports = module.exports;",
    ].join("\n"),
    footer: "\t\treturn module.exports;\n\t}\n});",
  },
});
